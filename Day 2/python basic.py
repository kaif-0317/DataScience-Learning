# Variables

name = "John"
age = 20

print("Name:", name)
print("Age:", age)


# Data type

integer = 10
floating = 5.5
text = "Python"
boolean = True

print(type(integer))
print(type(floating))
print(type(text))
print(type(boolean))


# Operators

a = 12
b = 4

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Modulus:", a % b)


# Loop

for i in range(1, 6):
    print(i)
    

# While loop

count = 1

while count <= 5:
    print(count)
    count += 1


# Function

def greet(name):
    print("Hello,", name)

greet("John")


